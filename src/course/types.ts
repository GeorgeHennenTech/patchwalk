// A playable lesson. Lessons are data: one file each, in a fixed shape, so chapters are easy to add and
// lessons can be taken in any order. Scripts live in docs/lessons/ and are converted to this shape.
import type { SynthState } from "../synth/params";

/** Everything a step's check can look at. Only facts the app knows exactly. */
export interface Snapshot {
  state: SynthState;
  /** Settings at the moment the step began. */
  start: SynthState;
  audioRunning: boolean;
  /** Notes sounding now (MIDI numbers). */
  held: number[];
  /** Count of note-ons since the step began, by input. */
  played: { mouse: number; keys: number; midi: number };
  /** Distinct notes played since the step began. */
  distinctNotes: number;
  holdOn: boolean;
  /** Seconds the current note has been held without a break. */
  heldSeconds: number;
  /** The longest any note has been held since the step began, in seconds: still counts after it is let go. */
  longestHeld: number;
  /** Lowest and highest value each setting has taken since the step began. */
  range: Partial<Record<keyof SynthState, { min: number; max: number }>>;
  /** How many times each setting has changed since the step began. */
  changes: Partial<Record<keyof SynthState, number>>;
  /** The most recent note played, or null if none yet. Used for readings that depend on the key. */
  lastNote: number | null;
  /** Things the learner clicked that are not synth settings (e.g. "acknowledged"). */
  flags: Record<string, boolean>;
}

export type Panel = "start" | "keyboard" | "hold" | "scope" | "spectrum" | "spectrogram" | "meter" | "beat" | "curve" | "envelope" | "envelope2" | "ack" | keyof SynthState;

export interface LessonStep {
  do: string;
  /** What appears for this step. Controls named here are spotlighted. */
  show: Panel[];
  /** What the learner should hear when it is right. */
  hear: string;
  /** Short description of what the app checks, shown as the target. */
  target: string;
  check: (s: Snapshot) => boolean;
  /** Settings applied when the step begins (e.g. to set up a starting point). */
  preset?: Partial<SynthState>;
  /** A sentence the guide says once the step is done, about what the learner actually did. Code-generated. */
  remark?: (s: Snapshot) => string | undefined;
}

/** One sound in a "hear it first" demo. Times are seconds from the start of the demo. */
export interface DemoTone {
  /** A basic shape at a frequency... */
  shape?: SynthState["shape"];
  hz?: number;
  /** ...or a whole patch (changes from the starting settings) played on a key. */
  patch?: Partial<SynthState>;
  note?: number;
  at: number;
  seconds: number;
  /** Level relative to the master volume, in dB. Default -8. Only for shape tones. */
  gainDb?: number;
}

/** A hidden sound to recreate by ear. Only the settings named in `match` are compared. */
export interface MatchRound {
  target: Partial<SynthState>;
  /** Settings the learner must get right, and the controls shown for the round. */
  match: (keyof SynthState)[];
  /** Where the learner's settings start for this round. */
  from: Partial<SynthState>;
  /** Controls shown for the round, when more than the compared ones are needed. Defaults to `match`. */
  controls?: (keyof SynthState)[];
}

export interface PlayableLesson {
  id: string;
  title: string;
  /** Lesson ids this builds on. Shown, never enforced. */
  buildsOn: string[];
  minutes: number;
  outcome: string;
  idea: string[];
  cardIds: string[];
  /** Settings the lesson starts from. */
  initial?: Partial<SynthState>;
  steps: LessonStep[];
  recap: string[];
  /** "Hear it first": a short before/after the learner can play at the top of the lesson. */
  demo?: { caption: string; tones: DemoTone[] };
  /** Match-by-ear rounds, taken after the steps. */
  rounds?: MatchRound[];
  /** Blind listening quiz generated by the app: name the wave shape, or say which of two tones is higher. */
  earCheck?: "shape" | "higher";
  /** Restrict the wave-shape picker to these shapes (e.g. a two-way "pure / bright" switch). */
  shapes?: readonly string[];
  /** Matching task in Serum, when there is one. */
  inSerum?: string;
}
